// Writes test/u256_vectors.wac: every U256 operation the EVM has, over edge values and random ones, with the
// answer computed by JavaScript's BigInt — an independent implementation of the same arithmetic.
//
//     node tools/u256-vectors.mjs
//
// Operands are in EVM stack order: `a` is the top of the stack. The seed is fixed so the file is stable.
import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const M = 1n << 256n;
const MAX = M - 1n;
const signed = (x) => (x >> 255n ? x - M : x);
const wrap = (x) => ((x % M) + M) % M;

let seed = 0x9e3779b97f4a7c15n;
function rnd64() {
  seed ^= seed << 13n; seed &= (1n << 64n) - 1n;
  seed ^= seed >> 7n;
  seed ^= seed << 17n; seed &= (1n << 64n) - 1n;
  return seed;
}
function rnd() {
  // Mix widths, so short operands and long ones both appear, and the division paths with one limb and many.
  const words = Number(rnd64() % 4n) + 1;
  let x = 0n;
  for (let i = 0; i < words; i++) x = (x << 64n) | rnd64();
  if (rnd64() % 5n === 0n) x = MAX - x;            // near the top
  return wrap(x);
}

// Every pair of these is a case for every binary op, so the list is short on purpose: each one is a boundary
// something has been, or could be, wrong at. (1 << 255) / ((1 << 128) + 7) is the pair that reaches the
// add-back step of Knuth's division, which random operands almost never do.
const edges = [0n, 1n, 31n, 256n, (1n << 64n) - 1n, 1n << 64n, (1n << 128n) + 7n, 1n << 255n, MAX];

const ops = {
  add: (a, b) => wrap(a + b),
  sub: (a, b) => wrap(a - b),
  mul: (a, b) => wrap(a * b),
  div: (a, b) => (b === 0n ? 0n : a / b),
  mod: (a, b) => (b === 0n ? 0n : a % b),
  sdiv: (a, b) => (b === 0n ? 0n : wrap(signed(a) / signed(b))),
  smod: (a, b) => (b === 0n ? 0n : wrap(signed(a) % signed(b))),
  addmod: (a, b, n) => (n === 0n ? 0n : (a + b) % n),
  mulmod: (a, b, n) => (n === 0n ? 0n : (a * b) % n),
  exp: (a, b) => { let r = 1n, x = a, e = b; while (e) { if (e & 1n) r = r * x % M; x = x * x % M; e >>= 1n; } return r; },
  signextend: (b, x) => {
    if (b >= 31n) return x;
    const bit = b * 8n + 7n, mask = (1n << (bit + 1n)) - 1n;
    return (x >> bit) & 1n ? x | (MAX ^ mask) : x & mask;
  },
  lt: (a, b) => BigInt(a < b), gt: (a, b) => BigInt(a > b),
  slt: (a, b) => BigInt(signed(a) < signed(b)), sgt: (a, b) => BigInt(signed(a) > signed(b)),
  eq: (a, b) => BigInt(a === b),
  and: (a, b) => a & b, or: (a, b) => a | b, xor: (a, b) => a ^ b, not: (a) => MAX ^ a,
  byte: (i, x) => (i >= 32n ? 0n : (x >> (8n * (31n - i))) & 0xffn),
  shl: (s, x) => (s >= 256n ? 0n : wrap(x << s)),
  shr: (s, x) => (s >= 256n ? 0n : x >> s),
  sar: (s, x) => (s >= 256n ? (signed(x) < 0n ? MAX : 0n) : wrap(signed(x) >> s)),
};
const small = ["byte", "shl", "shr", "sar", "signextend"];   // a first operand that is usually in range

// Edge cases are every pair (for ADDMOD and MULMOD, every (a, MAX - a, n)), so they are stored as one SHA-256
// per op over the 32-byte answers in order: a mismatch still names the op, and the file stays small. Random
// cases are stored whole, so a failure among them shows its operands.
const be32 = (x) => Buffer.from(x.toString(16).padStart(64, "0"), "hex");
const digests = [];
const rows = [];
for (const [name, f] of Object.entries(ops)) {
  const arity = f.length;
  const answers = [];
  if (arity === 2) for (const a of edges) for (const b of edges) answers.push(be32(f(a, b)));
  if (arity === 1) for (const a of edges) answers.push(be32(f(a)));
  if (arity === 3) for (const a of edges) for (const n of edges) answers.push(be32(f(a, MAX - a, n)));
  digests.push([name, "0x" + createHash("sha256").update(Buffer.concat(answers)).digest("hex")]);
  const pick = () => (small.includes(name) && rnd64() % 4n !== 0n ? rnd64() % 300n : rnd());
  for (let i = 0; i < 8; i++) {
    const a = pick(), b = rnd(), c = rnd();
    rows.push([name, a, b, c, arity === 3 ? f(a, b, c) : arity === 2 ? f(a, b) : f(a)]);
  }
}
const hex = (x) => "0x" + x.toString(16);
const out = `// Generated by tools/u256-vectors.mjs; do not edit. Every answer was computed with JavaScript's BigInt.
// Operands are in EVM stack order (\`a\` is the top).

/** The edge operands. Every op is run over every pair of them, or (a, MAX - a, n) for ADDMOD and MULMOD. */
export static string[] EDGES = [${edges.map((e) => `"${hex(e)}"`).join(", ")}];

/** Per op, SHA-256 of its edge answers as 32-byte big-endian words, in order. */
export static string[] EDGE_DIGESTS = [
${digests.map((d) => `  "${d[0]}", "${d[1]}",`).join("\n")}
];

/** ${rows.length} random cases: op, a, b, c, the answer. */
export static string[] VECTORS = [
${rows.map((r) => `  "${r[0]}", "${hex(r[1])}", "${hex(r[2])}", "${hex(r[3])}", "${hex(r[4])}",`).join("\n")}
];
`;
writeFileSync(new URL("../test/u256_vectors.wac", import.meta.url), out);
console.log(`${digests.length} digests, ${rows.length} random cases`);
